// Polish letters: base + mark. Accent rows are relative to the body top (row 0).
const ACUTE = { 'Ć': 'C', 'Ń': 'N', 'Ó': 'O', 'Ś': 'S', 'Ź': 'Z', 'ć': 'c', 'ń': 'n', 'ó': 'o', 'ś': 's', 'ź': 'z' };
const DOT = { 'Ż': 'Z', 'ż': 'z' };
const OGONEK = { 'Ą': 'A', 'Ę': 'E', 'ą': 'a', 'ę': 'e' };

const cache = new Map();

// Pixels of one character as [x, y] pairs (y from the body top) and its width
function glyph(char) {
    if (cache.has(char)) return cache.get(char);
    let base = char;
    let mark = null;
    if (ACUTE[char]) { base = ACUTE[char]; mark = 'acute'; }
    else if (DOT[char]) { base = DOT[char]; mark = 'dot'; }
    else if (OGONEK[char]) { base = OGONEK[char]; mark = 'ogonek'; }

    // Unknown characters: a capital-sized outline box, like a missing glyph in old systems
    const rows = GLYPHS[base] || g('####', '#..#', '#..#', '#..#', '#..#', '#..#', '####');
    const width = rows[0].length;
    const pixels = [];
    rows.forEach((row, y) => [...row].forEach((on, x) => { if (on === '#') pixels.push([x, y]); }));

    const capital = base === base.toUpperCase();
    const top = capital ? -2 : 0; // mark row, one free row above the capital or the x-height
    const mid = Math.floor((width - 1) / 2);
    if (mark === 'acute') pixels.push([mid + 1, top - 1], [mid, top]);
    if (mark === 'dot') pixels.push([mid, top]);
    if (mark === 'ogonek') pixels.push([width - 2, 7], [width - 1, 8]);

    const result = { pixels, width };
    cache.set(char, result);
    return result;
}

export function measureText(text, { bold = false } = {}) {
    const chars = [...text];
    if (!chars.length) return 0;
    return chars.reduce((sum, char) => sum + glyph(char).width + (bold ? 1 : 0), 0) + chars.length - 1;
}

// Bold is the old bitmap-font trick: every pixel again one to the right
export function drawText(ctx, text, x, y, { color = '#FFF', bold = false } = {}) {
    ctx.fillStyle = color;
    let left = x;
    for (const char of text) {
        const { pixels, width } = glyph(char);
        pixels.forEach(([px, py]) => ctx.fillRect(left + px, y + TOP + py, bold ? 2 : 1, 1));
        left += width + (bold ? 1 : 0) + 1;
    }
}

// Pixels of a single character, for sprites that place letters by hand
export function glyphPixels(char) {
    return glyph(char);
}
